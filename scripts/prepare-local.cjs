// Compatibility redirects for VS Code Live Server and other file-only servers.
// Generated directories are ignored by Git and never shipped to production.
const fs = require('node:fs');
const path = require('node:path');
const pages = require('../routes.js');
const root = path.resolve(__dirname, '..');
const marker = '<!-- NARI local route: generated by scripts/prepare-local.cjs -->';

for (const page of pages) {
  const dir = path.join(root, page);
  const target = path.join(dir, 'index.html');
  if (fs.existsSync(dir) && (!fs.existsSync(target) || !fs.readFileSync(target, 'utf8').includes(marker))) {
    throw new Error('Refusing to overwrite an existing directory: ' + page);
  }
  const destination = '../' + path.basename(page) + '.html';
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(target, `${marker}
<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="robots" content="noindex, nofollow"><title>Opening NARI Health</title>
<noscript><meta http-equiv="refresh" content="0;url=${destination}"></noscript></head><body>
<script>location.replace(${JSON.stringify(destination)} + location.search + location.hash);</script>
<a href="${destination}">Continue to NARI Health</a></body></html>
`);
}
console.log('Local routes ready. Open http://localhost:5500/member-login');
